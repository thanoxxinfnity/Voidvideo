"""Build and push the Pixal3D Gradio UI as a self-contained Kaggle GPU kernel.

The kernel compiles the TRELLIS.2 CUDA extensions, patches Pixal3D, then serves
pixal3d_ui/app.py with a public gradio.live link (look for "public URL" in the
kernel log). It exits by itself after IDLE_MINUTES idle so the GPU quota is not
burned.

Usage:
    export KAGGLE_API_TOKEN=...            # or KAGGLE_USERNAME + KAGGLE_KEY
    python scripts/push_pixal3d_ui_to_kaggle.py [--kernel-id user/slug] [--idle 30] [--build-only]
"""
import argparse
import json
import os
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(ROOT, "pixal3d_ui")
FILES = ("patches.py", "backend.py", "app.py")

TEMPLATE = r'''# VoidVideo 3D UI (Pixal3D) - generated by scripts/push_pixal3d_ui_to_kaggle.py
import glob, os, subprocess, sys, threading, time, traceback
START = time.time()
UI_DIR = "/kaggle/tmp/ui"; REPO = "/kaggle/tmp/pixal3d"; TRELLIS = "/kaggle/tmp/trellis2"
IDLE_MINUTES = "@IDLE@"
FILES = @FILES@

def log(*a):
    print("[%6.1fm]" % ((time.time() - START) / 60), *a, flush=True)

def sh(cmd, check=False):
    log("$", cmd)
    r = subprocess.run(cmd, shell=True, executable="/bin/bash")
    if check and r.returncode != 0:
        log("FAILED rc=%s: %s" % (r.returncode, cmd)); sys.exit(1)
    return r

def main():
    os.makedirs("/kaggle/tmp", exist_ok=True); os.makedirs("/kaggle/working/out", exist_ok=True)
    os.makedirs(UI_DIR, exist_ok=True)
    for name, text in FILES.items():
        open(os.path.join(UI_DIR, name), "w").write(text)
    sh("nvidia-smi --query-gpu=name,memory.total --format=csv,noheader")
    sh("git clone --depth 1 -b master https://github.com/TencentARC/Pixal3D " + REPO, check=True)
    sys.path.insert(0, UI_DIR)
    import patches
    patches.apply_repo_patches(REPO)   # raises (and aborts before any compile) if upstream moved
    log("patches applied")
    # Prebuilt wheels from an earlier run (dataset "pixal3d-wheels"), if attached: skips ~45 min of CUDA compiles.
    wheels = [w for w in glob.glob("/kaggle/input/**/*.whl", recursive=True)
              if any(k in os.path.basename(w) for k in ("o_voxel", "cumesh", "flex_gemm", "nvdiffrast", "natten"))]
    py_tag = "cp%d%d" % sys.version_info[:2]
    wheels = [w for w in wheels if py_tag in w]
    if len(wheels) >= 5:
        log("installing %d prebuilt wheels" % len(wheels))
        sh("pip install -q --no-deps " + " ".join("'%s'" % w for w in wheels), check=True)
        sh("pip install -q lpips easydict ninja")
    else:
        sh("git clone --depth 1 -b main --recursive https://github.com/microsoft/TRELLIS.2.git " + TRELLIS, check=True)
        sh("cd %s && . ./setup.sh --basic --nvdiffrast --cumesh --o-voxel --flexgemm" % TRELLIS)
        sh("NATTEN_CUDA_ARCH='7.5' NATTEN_N_WORKERS=4 pip install -q natten==0.21.0 --no-build-isolation")
        # keep the compiled wheels in the kernel output so they can become a dataset
        sh("mkdir -p /kaggle/working/wheels && find $(pip cache dir)/wheels -name '*.whl' -exec cp -n {} /kaggle/working/wheels/ \\; ; ls -la /kaggle/working/wheels")
    sh("pip install -q -r %s/requirements.txt" % REPO)  # may fail on the MoGe line; pins are re-applied below
    sh("pip install -q https://github.com/LDYang694/Storages/releases/download/20260430/utils3d-0.0.2-py3-none-any.whl")
    sh("pip install -q git+https://github.com/microsoft/MoGe.git")
    sh("pip install -q rembg onnxruntime")
    # Pixal3D needs transformers==4.57.3 (DINOv3ViTModel.layer was renamed in 5.x). The requirements install
    # above fails as a whole on the MoGe line, which silently leaves transformers 5.x - force the pin.
    sh("sed 1d %s/requirements.txt > /kaggle/tmp/req_nomoge.txt && pip install -q -r /kaggle/tmp/req_nomoge.txt" % REPO)
    sh("pip install -q transformers==4.57.3")
    r = sh("python -c 'import transformers; assert transformers.__version__ == \"4.57.3\", transformers.__version__; print(\"transformers\", transformers.__version__)'")
    if r.returncode != 0:
        log("transformers pin FAILED - not starting UI (saves GPU quota)"); return
    r = sh("cd %s && ATTN_BACKEND=sdpa python -c 'import o_voxel, torch, natten; import inference; print(\"imports ok\")'" % REPO)
    if r.returncode != 0:
        log("IMPORT CHECK FAILED - not starting UI (saves GPU quota)"); return
    log("env ready; starting UI")
    env = dict(os.environ, SHARE="1", WARMUP="1", IDLE_MINUTES=IDLE_MINUTES, PIXAL3D_REPO=REPO,
               PIXAL3D_OUT="/kaggle/working/out", ATTN_BACKEND="sdpa", PYTHONUNBUFFERED="1")
    p = subprocess.Popen([sys.executable, "-u", os.path.join(UI_DIR, "app.py")], env=env,
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    for line in p.stdout:
        print(line, end="", flush=True)
        if "public URL" in line:
            open("/kaggle/working/public_url.txt", "w").write(line)
    log("UI exited rc", p.wait())

if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        pass
    except BaseException:
        traceback.print_exc()
    log("finished; exiting so the GPU is released")
    sys.stdout.flush()
    os._exit(0)
'''


def build(out_dir, kernel_id, idle):
    files = {n: open(os.path.join(UI, n)).read() for n in FILES}
    code = TEMPLATE.replace("@FILES@", repr(files)).replace("@IDLE@", str(idle))
    compile(code, "kernel.py", "exec")
    slug = kernel_id.split("/")[1]
    with open(os.path.join(out_dir, slug + ".py"), "w") as fh:
        fh.write(code)
    meta = {"id": kernel_id, "title": slug.replace("-", " "), "code_file": slug + ".py",
            "language": "python", "kernel_type": "script", "is_private": True,
            "enable_gpu": True, "enable_tpu": False, "enable_internet": True,
            "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
            "model_sources": [], "machine_shape": "NvidiaTeslaT4"}
    with open(os.path.join(out_dir, "kernel-metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2)
    return len(code)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kernel-id", default="upsschool/voidvideo-3d-ui")
    ap.add_argument("--idle", type=int, default=30, help="auto-exit after N idle minutes")
    ap.add_argument("--build-only", action="store_true")
    ap.add_argument("--out-dir", default=None)
    a = ap.parse_args()
    out = a.out_dir or tempfile.mkdtemp(prefix="p3dui_")
    os.makedirs(out, exist_ok=True)
    size = build(out, a.kernel_id, a.idle)
    print("built %s (%d bytes)" % (out, size))
    if size > 1_000_000:
        sys.exit("kernel source must be < 1MB")
    if a.build_only:
        return
    from kaggle.api.kaggle_api_extended import KaggleApi
    api = KaggleApi(); api.authenticate()
    resp = api.kernels_push(out)
    if getattr(resp, "error", None):
        sys.exit("Kaggle rejected the push: %s" % resp.error)
    print("pushed:", resp.url, "version", resp.version_number)


if __name__ == "__main__":
    main()
